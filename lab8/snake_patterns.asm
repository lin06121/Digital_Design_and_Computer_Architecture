#  环境 : MARS, 内存配置选 "Compact, Data at Address 0"
#
#  功能 : 把 12 张"单个灯珠"的图案 (pattern) 依次写到 MMIO 显示寄存器 0x7FF0,
#         于是 4 位数码管上会有一个亮点按 "蛇形" 路径逐格爬行。两张图案之间用
#         一个 200 万次的大延迟循环减速 (loopcnt = 0x001e8484), 否则太快看不清。
#
#  I/O :
#    0x7FF0 (out, 28bit) = 7 段显示寄存器, sw $t0, 0x7ff0($0) 即刷新显示。
#
#  说明 : 本文件对应的内存 dump 是 insmem_h.txt (这部分 .text) 与
#         datamem_h.txt (.data 那 13 个字)。part 2 要改成读开关调速的版本,
#         见 snake_patterns_speed.asm。
#============================================================================

.data
# 12 个图案: 每个只有一位为 1 (点在某个数码管的某一段上), 依次爬行
pattern: .word 0x00200000,0x00004000,0x00000080,0x00000001,0x00000002,0x00000004,0x00000008,0x00000400,0x00020000,0x01000000,0x02000000,0x04000000
# 延迟循环计数值 (越大蛇爬得越慢)
loopcnt: .word 0x001e8484

.text
   lw $t3, loopcnt      # 把大循环计数值载入 $t3 (让蛇别爬太快)
   addi $t5,$0,48       # 显示图案的总字节长度 12 个字 = 48 字节

restart:                # 一轮爬完, 从头再来
   addi $t4,$0,0        # $t4 = 当前字节偏移, 归 0

forward:
   beq $t5,$t4, restart # 偏移 == 48 ? 是 -> 回到 restart 重头开始
   lw $t0,0($t4)        # $t0 = pattern[$t4/4]
   sw  $t0, 0x7ff0($0)  # 把图案写到 MMIO 显示寄存器 0x7FF0

   addi $t4, $t4, 4     # 偏移 += 4 (下一个字)
   addi $t2, $0, 0      # 清零延迟计数器 $t2

wait:
   beq $t2,$t3,forward  # 延迟计数到了 $t3 ? 是 -> 显示下一张图案
   addi  $t2, $t2, 1    # 延迟计数器 +1
   j wait               # 继续空转